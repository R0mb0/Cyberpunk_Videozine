/* Dummy function for the RayTracker "context" dialog box (just to show
   the user the progress.... */

void context(str)
char *str;
{
   printf("\nProcesssing: %s...",str);
}

/* Compare two strings up to the length of the second string */

int stris(a,b)
char *a,*b;
{
   return (strnicmp(a,b,strlen(b))==0);
}

/* This function parses a 3D Studio "ASCII" file as generated with the
   menu option "Save ASCII". This code is an adaption of the 3D Studio
   ASCII file loading code in RayTracker.
      
   It warns for tokens it does not recognize, like "Background" and
   similar. This has no impact on the conversion and is just information. */

void load_3ds(innamn,utnamn)
char *innamn,*utnamn;
{
   FILE *in, *ut;
   struct {float x,y,z;} p1;
   char *p;
   int vcount, fcount;

   load_defaultfile();
   
   in = fopen(innamn,"r");
   ut = fopen(utnamn,"w");
   
   if (!in || !ut)
   {
      printf("Could not open file(s)");
      exit(-1);
   }
   
   while (!feof(in))
   {
      if (!already_read)
      {  
         do 
         {
            fgets(attribute,1000,in);
            attribute[strlen(attribute)-1] = 0;
         } while ((attribute[0] <= 32) && ! feof(in));
      }
      already_read = FALSE;
      
      /* Empty row: End of things... */
      if (attribute[0] == 0)
      {
      }
      else
      if (stris(attribute,"Ambient light"))
      {
/*       
         ambient_intensity = 1;
      
         p = strstr(attribute,"Red=") + 4;
         sscanf(p,"%g",&ambient_light.r);
         p = strstr(attribute,"Green=") + 6;
         sscanf(p,"%g",&ambient_light.g);
         p = strstr(attribute,"Blue=") + 5;
         sscanf(p,"%g",&ambient_light.b);
*/       
      }
      else
      if (stris(attribute,"Named object:"))
      {
         strtok(attribute,":");
         p = strtok(NULL,":");
         strcpy(object_name,p+1);
      
         context(object_name);
         
         un_space(object_name);
      } 
      else
      if (stris(attribute,"Tri-mesh"))
      { 
         strtok(attribute,":");
         p = strtok(NULL,":");
         sscanf(p,"%d",&vcount);
         
         p = strtok(NULL,":");
         sscanf(p,"%d",&fcount);
         
         fprintf(ut, "%s %d %d\n", object_name, vcount, fcount);
      }
      else
      if (stris(attribute,"Vertex list"))
      {
         context("Vertex list...");
      }
      else
      if (stris(attribute,"Vertex"))
      { 
         long px,py,pz;
         
         p = strstr(attribute,"X:") + 3;
         sscanf(p,"%g",&p1.x);
         p = strstr(attribute,"Y:") + 3;
         sscanf(p,"%g",&p1.y);
         p = strstr(attribute,"Z:") + 3;
         sscanf(p,"%g",&p1.z);

         px = p1.x * scale;
         pz = p1.y * scale;
         py = p1.z * scale;         
         
         fprintf(ut,"%ld %ld %ld\n",px,py,pz);
      }
      else
      if (stris(attribute,"Face list:"))
      { 
         context("Face list");
      } 
      else
      if (stris(attribute,"Face "))
      {
         int t,v1,v2,v3;
         
         p = strstr(attribute,"A:") + 2;
         sscanf(p,"%d",&v1);
         p = strstr(attribute,"B:") + 2;
         sscanf(p,"%d",&v2);
         p = strstr(attribute,"C:") + 2;
         sscanf(p,"%d",&v3);
         
         p = strstr(attribute,"Mtl:") + 4;
         un_space(p);
         t = add_texture(p);
         
         fprintf(ut,"%d 3 %d %d %d\n",t,v1,v2,v3);
         
         do 
         {
            fgets(attribute,1000,in);
            attribute[strlen(attribute)-1] = 0;
         } while ((attribute[0] <= 32) && ! feof(in));
         
         /* Is it a flat face? */
         if (!stris(attribute,"Smooth"))
         {
            already_read = TRUE;
         }  
      }
      else
      if (stris(attribute,"Camera ("))
      {
      }
      else
      if (stris(attribute,"Position:"))
      {

      }
      else
      if (stris(attribute,"Target:"))
      {
      }
      else
      if (stris(attribute,"Direct light"))
      {
      }
      else
      if (stris(attribute,"Light color:"))
      {  
      } 
      else
      if (stris(attribute,"Spotlight to:"))
      {
      }
      else
      if (stris(attribute,"Falloff size:"))
      {
      }
      else
      if (stris(attribute,"Bank angle:"))
      { 
      }
      else
      {
         strtok(attribute," ");
                        
         printf("Unrecognized token in 3DS File\n'%s'\n(might be wrong file type)\a",attribute);
      }
   }

   /* If it was an object... end it nicely... */

   save_defaultfile();
   
   fclose(ut);
   fclose(in);
}
