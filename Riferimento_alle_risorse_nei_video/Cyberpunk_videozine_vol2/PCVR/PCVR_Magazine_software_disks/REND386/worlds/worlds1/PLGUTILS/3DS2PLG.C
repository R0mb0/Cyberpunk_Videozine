/* Some stuff to put the materials in... */

char materials[MAX_MATERIALS][MAX_NAME_LENGTH];
int materialsn[MAX_MATERIALS];
char last_material[MAX_NAME_LENGTH] = "Oy Oy Oy";
int nlast_material = 0;

/* Changes all underscores to spaces.... or was it the other way around?? */

char un_space(str)
char *str;
{
   while (*str)
   {
      if (*str == ' ') *str = '_';
      str++;
   }
}

int n_materials = 0;

/* Function returns the color number for the material string in p */
/* and asks if not defined previously */

int add_texture(p)
char *p;
{
   int i, zook, wook;
   
   /* For speed... */
   
   if (stricmp(last_material,p) == 0)
      return nlast_material;
   
   for (i = 0; i < n_materials; i++)
   {
      if (stricmp(materials[i],p) == 0)
      {
         strcpy(last_material, p);
         nlast_material = materialsn[i];
         
         return nlast_material;
      }
   }
   
   strcpy(materials[n_materials],p);
   strcpy(last_material, p);
   
   zook = 0;
   printf("\nMaterial %s Fixed/Cosine/Metal/Glass: ",p);
      
   switch (getch())
   {
      case 'f':
      case 'F': 
         zook = 0x0000;
         printf("\nFixed color index ->");
         scanf("%d",&wook);
         zook |= wook;
            
         break;
      case 'm':
      case 'M': 
         zook = 0x2000;
         shocol();
         printf("\nMetal base color: (1 - 15) ->");
         scanf("%d",&wook);            
         zook |= ((wook << 8) & 0x0f00);
         printf("\nColor cycle offset (0 - 255) ->");
         scanf("%d",&wook);            
         zook |= (0x00ff);
         break;                        
            
      case 'g':
      case 'G': 
         zook = 0x3000;
         shocol();
         printf("\nGlass base color: (1 - 15) ->");
         scanf("%d",&wook);            
         zook |= ((wook << 8) & 0x0f00);
         printf("\nColor cycle offset (0 - 255) ->");
         scanf("%d",&wook);            
         zook |= (0x00ff);
         break;                        
         
      default:
         zook = 0x1000;
         shocol();
         printf("\nCosine base color: (1 - 15) ->");
         scanf("%d",&wook);            
         zook |= ((wook << 8) & 0x0f00);
         printf("\nBase color brightness (0 - 255) ->");
         scanf("%d",&wook);            
         zook |= (0x00ff);
         break;                        
   }
      
   materialsn[n_materials] = zook;
   
   nlast_material = zook;
   
   printf("\nResulting cidx = %d (%d)\n",zook,nlast_material);
   
   n_materials++;
   
   if (n_materials >= MAX_MATERIALS)
   {
      printf("KerWham!\a Oh no!\ Repent!\a The end is near!\a");
      printf("You have tried to make more than %d materials!", MAX_MATERIALS);
      exit(0);
   }
   
   return zook;
}

/* Load a defaultfile 

   The format of the file is the simplest possible: 
   Each line defines a material. The material name has all spaces 
   replaced with underscores, and is followed by the color value
   to use for it. Heavy, eh? 

*/

void load_defaultfile()
{
   FILE *fp;
   
   fp = fopen("material.def","r");
   
   if (!fp)
   {
      printf("\nNo material database exist - new created!");      
      return;
   }
   
   while (fscanf(fp,"%s %d",materials[n_materials],&materialsn[n_materials])
           == 2)
   {  
      n_materials++;
      
      if (n_materials >= MAX_MATERIALS)
      {
         printf("KerWham!\a Oh no!\a Please!\a Spare me this!\a Oh Oh!\a");
         printf("MATERIALS.DEF has more than %d materials!", MAX_MATERIALS);
         exit(0);
      }  
   }  
   fclose(fp);
}

/* Save a defaultfile */

void save_defaultfile()
{
   int i;
   FILE *fp;
   
   fp = fopen("material.def","w");
   
   if (!fp)
   {
      printf("KerWham! Could not save material database!!??!!\n");
      exit(0);
   }

   /* If I had the strength I would probably test for diskfull in the
      below for loop, but I wouldn't wanna make my fingers shorter than
      they already are, and by the way I have wasted enough time while
      writing this pointless comment so it would have been even easier
      if I had written the bloody "if (fprintf.... != 2) go_boom()" 
      in the first place, but now it is too late, I wont do it!!! */
   
   for (i = 0; i < n_materials; i++)
   {
      fprintf(fp,"%s %d\n",materials[i],materialsn[i]);
   }
   
   fclose(fp);
}


